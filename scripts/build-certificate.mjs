// Writes the two files the volunteer certificate is served as, from the approved design in
// certificate/:
//
//   certificate/template.html    ->  assets/certificate.html   ({{ASSET:…}} becomes a data URI)
//   certificate/certificate.css  ->  certificate.css
//
//   node scripts/build-certificate.mjs        (npm run build:cert)
//
// Both outputs are committed, and tests/certificate-template.spec.ts fails when either is stale,
// the same deal as index.html and the wallet bundle. Edit the sources, never the outputs.
//
// The images travel inside the file because the certificate is opened from two origins - the
// booking app and volunteer.micromobility.sa - and a data: URI needs no copy of them on either
// (img-src allows data: in both policies). The fonts are not inlined: the page uses Space Grotesk
// and IBM Plex Sans Arabic, which each app already serves and names through the template's
// {{fonts}}.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const src = (...p) => join(root, 'certificate', ...p);

const NOTE = (from) => `<!-- Generated by scripts/build-certificate.mjs from certificate/${from}. Edit that file. -->\n`;

/** certificate/assets/<name> as a data: URI. SVG goes in base64: it carries quotes and '#'. */
function asset(name) {
  return `data:image/svg+xml;base64,${readFileSync(src('assets', name)).toString('base64')}`;
}

// ── certificate.css: the stylesheet ───────────────────────────────────────────────────────────
let css = readFileSync(src('certificate.css'), 'utf8');
if (/@font-face\s*\{/.test(css)) throw new Error('build:cert: certificate/certificate.css declares a font; the page uses the two families each app already serves ({{fonts}})');
css = `/* Generated by scripts/build-certificate.mjs from certificate/certificate.css. Edit that file. */\n${css}`;

// ── assets/certificate.html: the markup, with the brand assets in it ───────────────────────────
let html = readFileSync(src('template.html'), 'utf8');
html = html.replace(/<!--\s*\n\s*SOURCE\.[\s\S]*?-->\n/, '');
html = html.replace(/\{\{ASSET:([a-z0-9.-]+)\}\}/g, (_, name) => asset(name));
if (/\{\{ASSET:/.test(html)) throw new Error('build:cert: an {{ASSET:…}} name is not [a-z0-9.-]');
html = html.replace(/^<!doctype html>\n/i, `<!doctype html>\n${NOTE('template.html')}`);

writeFileSync(join(root, 'certificate.css'), css);
writeFileSync(join(root, 'assets', 'certificate.html'), html);
console.log(`build:cert: certificate.css ${(css.length / 1024).toFixed(1)} KB, assets/certificate.html ${(html.length / 1024).toFixed(1)} KB`);
